const normalize = (value) => String(value || "").trim().toLowerCase();

const townsForRegion = (region) => GHANA_TOWNS_BY_REGION[region] || [];

const isValidTown = (region, town) =>
  townsForRegion(region).some((candidate) => normalize(candidate) === normalize(town));

const GHANA_TOWNS = Object.freeze(
  GHANA_REGIONS.flatMap((region) =>
    townsForRegion(region).map((town) => Object.freeze({ region, town })),
  ),
);

const regionForTown = (town) => {
  const match = GHANA_TOWNS.find((entry) => normalize(entry.town) === normalize(town));
  return match ? match.region : undefined;
};

module.exports = {
  GHANA_TOWNS,
  GHANA_TOWNS_BY_REGION,
  isValidTown,
  regionForTown,
  townsForRegion,
};
